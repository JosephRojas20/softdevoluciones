CREATE TABLE productos (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nombre VARCHAR(150) NOT NULL,
                           descripcion VARCHAR(500),
                           activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE compras (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         fecha TIMESTAMP NOT NULL,
                         total NUMERIC(12, 2) NOT NULL,
                         estado VARCHAR(30) NOT NULL,
                         usuario_id BIGINT NOT NULL,

                         CONSTRAINT fk_compras_usuario
                             FOREIGN KEY (usuario_id)
                                 REFERENCES usuarios(id),

                         CONSTRAINT ck_compras_total
                             CHECK (total >= 0)
);

CREATE INDEX idx_compras_usuario
    ON compras(usuario_id);

CREATE TABLE detalles_compra (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 compra_id BIGINT NOT NULL,
                                 producto_id BIGINT NOT NULL,
                                 cantidad INTEGER NOT NULL,
                                 precio_unitario NUMERIC(12, 2) NOT NULL,

                                 CONSTRAINT fk_detalles_compra_compra
                                     FOREIGN KEY (compra_id)
                                         REFERENCES compras(id),

                                 CONSTRAINT fk_detalles_compra_producto
                                     FOREIGN KEY (producto_id)
                                         REFERENCES productos(id),

                                 CONSTRAINT ck_detalles_compra_cantidad
                                     CHECK (cantidad > 0),

                                 CONSTRAINT ck_detalles_compra_precio
                                     CHECK (precio_unitario >= 0)
);

CREATE INDEX idx_detalles_compra_compra
    ON detalles_compra(compra_id);

CREATE TABLE solicitudes_devolucion (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        compra_id BIGINT NOT NULL,
                                        usuario_id BIGINT NOT NULL,
                                        fecha_solicitud TIMESTAMP NOT NULL,
                                        estado VARCHAR(20) NOT NULL,
                                        motivo VARCHAR(30) NOT NULL,
                                        comentario VARCHAR(1000),
                                        observacion_operador VARCHAR(1000),
                                        importe NUMERIC(12, 2) NOT NULL,

                                        CONSTRAINT fk_solicitudes_compra
                                            FOREIGN KEY (compra_id)
                                                REFERENCES compras(id),

                                        CONSTRAINT fk_solicitudes_usuario
                                            FOREIGN KEY (usuario_id)
                                                REFERENCES usuarios(id),

                                        CONSTRAINT ck_solicitudes_estado
                                            CHECK (
                                                estado IN (
                                                           'SOLICITADA',
                                                           'EN_REVISION',
                                                           'APROBADA',
                                                           'RECHAZADA',
                                                           'COMPLETADA'
                                                    )
                                                ),

                                        CONSTRAINT ck_solicitudes_motivo
                                            CHECK (
                                                motivo IN (
                                                           'DEFECTUOSO',
                                                           'PRODUCTO_INCORRECTO',
                                                           'INCOMPLETO',
                                                           'OTRO'
                                                    )
                                                ),

                                        CONSTRAINT ck_solicitudes_importe
                                            CHECK (importe >= 0),

                                        CONSTRAINT ck_solicitudes_rechazo
                                            CHECK (
                                                estado <> 'RECHAZADA'
                                                    OR (
                                                    observacion_operador IS NOT NULL
                                                        AND LENGTH(TRIM(observacion_operador)) > 0
                                                    )
                                                )
);

CREATE INDEX idx_solicitudes_usuario
    ON solicitudes_devolucion(usuario_id);

CREATE INDEX idx_solicitudes_estado
    ON solicitudes_devolucion(estado);

CREATE INDEX idx_solicitudes_motivo
    ON solicitudes_devolucion(motivo);

CREATE INDEX idx_solicitudes_fecha
    ON solicitudes_devolucion(fecha_solicitud);

CREATE TABLE detalles_devolucion (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     solicitud_id BIGINT NOT NULL,
                                     detalle_compra_id BIGINT NOT NULL,
                                     cantidad INTEGER NOT NULL,
                                     importe NUMERIC(12, 2) NOT NULL,

                                     CONSTRAINT fk_detalles_devolucion_solicitud
                                         FOREIGN KEY (solicitud_id)
                                             REFERENCES solicitudes_devolucion(id),

                                     CONSTRAINT fk_detalles_devolucion_compra
                                         FOREIGN KEY (detalle_compra_id)
                                             REFERENCES detalles_compra(id),

                                     CONSTRAINT uq_solicitud_detalle_compra
                                         UNIQUE (solicitud_id, detalle_compra_id),

                                     CONSTRAINT ck_detalles_devolucion_cantidad
                                         CHECK (cantidad > 0),

                                     CONSTRAINT ck_detalles_devolucion_importe
                                         CHECK (importe >= 0)
);

CREATE INDEX idx_detalles_devolucion_compra
    ON detalles_devolucion(detalle_compra_id);